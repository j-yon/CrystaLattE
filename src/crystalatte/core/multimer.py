from __future__ import annotations

from dataclasses import dataclass, field
from functools import cached_property
from itertools import combinations

import numpy as np
import qcelemental as qcel
from numpy.typing import NDArray
from scipy.spatial.distance import cdist, pdist

from .generation import GenerationInfo
from .sym_ops import SymOp, SymOpList

# past 6 who really cares about names
_NAMES = {1: "monomer", 2: "dimer", 3: "trimer", 4: "tetramer", 5: "pentamer", 6: "hexamer"}


def order_name(N: int) -> str:
    """Get explicit multimer name for a given order N"""
    return _NAMES.get(N, f"{N}mer")


@dataclass
class ASU:
    """An asymmetric unit: the smallest portion of a crystal from which the full unit cell follows

    :param _atoms: Atomic symbols of the atoms in the ASU
    :param _positions: Fractional coordinates of those atoms
    """

    _atoms: list[str]
    _positions: NDArray[np.float64]

    def __post_init__(self):
        """Validate that atoms and positions describe the same set

        :raises ValueError: If the atom/position counts disagree
        """
        if len(self._atoms) != len(self._positions):
            raise ValueError("Number of atoms must match number of positions")

    @property
    def atoms(self) -> list[str]:
        return self._atoms

    @property
    def positions(self) -> NDArray:
        return self._positions


@dataclass
class Monomer:
    """A complete molecule in the crystal

    :param _symbols: Atomic symbols of the atoms in the monomer
    :param _frac_coords: Fractional coordinates of the monomer atoms
    :param _cart_coords: Cartesian coordinates of the monomer atoms in Angstroms
    :param _centroid_frac: Monomer centroid in fractional coordinates
    :param _centroid_cart: Monomer centroid in Cartesian coordinates
    :param _symop: Symmetry operation (:class:`SymOp`) that generates this monomer from the reference monomer
    """

    _symbols: list[str]
    _frac_coords: NDArray[np.float64]
    _cart_coords: NDArray[np.float64]
    _centroid_frac: NDArray[np.float64]
    _centroid_cart: NDArray[np.float64]
    _symop: SymOp | None = None

    def __repr__(self) -> str:
        return (
            f"Monomer(symbols={self._symbols}, "
            f"centroid_cart={self._centroid_cart}, SymOp={self._symop})"
        )

    @property
    def symbols(self) -> list[str]:
        return self._symbols

    @property
    def frac_coords(self) -> NDArray[np.float64]:
        return self._frac_coords

    @property
    def cart_coords(self) -> NDArray[np.float64]:
        return self._cart_coords

    @property
    def centroid_frac(self) -> NDArray[np.float64]:
        return self._centroid_frac

    @property
    def centroid_cart(self) -> NDArray[np.float64]:
        return self._centroid_cart

    @property
    def symop(self) -> SymOp | None:
        return self._symop

    def to_molecule(self) -> qcel.models.Molecule:
        """Convert to a QCElemental :class:`qcelemental.models.Molecule`

        :returns: Monomer as a :class:`qcelemental.models.Molecule`
        """
        return qcel.models.Molecule(
            symbols=self._symbols,
            geometry=(self._cart_coords / qcel.constants.bohr2angstroms).flatten(),
        )


@dataclass
class Multimer:
    """A unique cluster of N monomers in the crystal, generated by symmetry

    :param _monomers: :class:`Monomer` instances making up this multimer
    :param _sym_ops: :class:`SymOp` instances that generate this multimer
    :param _multiplicity: How many times this multimer occurs in the crystal by symmetry
    :param _generation: :class:`GenerationInfo` of the run that produced it, ``None`` if built by hand
    :ivar _geometric_mean: Geometric mean of the inter-monomer centroid distances
    """

    _monomers: list[Monomer]
    _sym_ops: SymOpList
    _multiplicity: int = 1
    _generation: GenerationInfo | None = None
    _geometric_mean: float = field(init=False)

    def __post_init__(self):
        """Compute the geometric mean of the inter-monomer centroid distances"""
        dists = pdist([m._centroid_cart for m in self._monomers])
        self._geometric_mean = float(np.prod(dists) ** (1 / len(dists)))

    @classmethod
    def from_parts(
        cls,
        monomers: list[Monomer],
        sym_ops: SymOpList,
        multiplicity: int,
        geometric_mean: float,
        generation: GenerationInfo | None = None,
    ) -> Multimer:
        """Create a :class:`Multimer` whose geometric mean was already computed

        :param monomers: :class:`Monomer` instances making up the multimer
        :param sym_ops: :class:`SymOp` instances that generate the multimer
        :param multiplicity: How many times the multimer occurs in the crystal by symmetry
        :param geometric_mean: Geometric mean of the inter-monomer centroid distances, as ``__post_init__`` computes it
        :param generation: :class:`GenerationInfo` of the run that produced it, ``None`` if built by hand
        :returns: the :class:`Multimer`
        """
        multimer = cls.__new__(cls)
        multimer._monomers = monomers
        multimer._sym_ops = sym_ops
        multimer._multiplicity = multiplicity
        multimer._generation = generation
        multimer._geometric_mean = geometric_mean
        return multimer

    def __eq__(self, value: object, /) -> bool:
        if not isinstance(value, Multimer):
            return NotImplemented
        if len(self._monomers) != len(value._monomers):
            return False
        return all(
            m1._symbols == m2._symbols
            and np.allclose(m1._centroid_cart, m2._centroid_cart, atol=1e-3)
            and m1._symop == m2._symop
            for m1, m2 in zip(self._monomers, value._monomers)
        )

    def __repr__(self) -> str:
        return (
            f"Multimer(Monomers={self._monomers}, "
            f"multiplicity={self._multiplicity}, "
            f"geometric_mean={self._geometric_mean:.2f} Å)"
        )

    @property
    def monomers(self) -> list[Monomer]:
        return self._monomers

    @property
    def sym_ops(self) -> SymOpList:
        return self._sym_ops

    @property
    def multiplicity(self) -> int:
        return self._multiplicity

    @multiplicity.setter
    def multiplicity(self, value: int):
        self._multiplicity = value

    @property
    def geometric_mean(self) -> float:
        return self._geometric_mean

    @cached_property
    def min_separation(self) -> float:
        """Distance in Angstroms between the closest two atoms belonging to different monomers"""
        return float(min(cdist(a._cart_coords, b._cart_coords).min() for a, b in combinations(self._monomers, 2)))

    @property
    def generation(self) -> GenerationInfo | None:
        return self._generation

    @cached_property
    def id(self) -> str:
        """Identifier from the order name and the hash of the multimer geometry

        The hash is of the representative's absolute Cartesian geometry, so it depends on the
        frame. Ids are stable for the same code, CIF and settings, but change if deduplication
        picks a different representative of the orbit. That fails safe: backends redo the work
        under the new id and never assign a result to the wrong multimer.
        """
        return f"{order_name(len(self._monomers))}-{self.to_molecule().get_hash()[:16]}"

    @property
    def weight(self) -> float:
        """Contribution of this multimer's interaction energy to the lattice energy per formula unit

        The energy per cell is ``(1/N) sum_r n_r sum_{C containing r} dE_C``, with ``n_r`` the
        molecules per cell generated from reference ``r``. Candidates anchored on reference ``r``
        enumerate exactly the clusters containing ``r``, so ``a_r`` (:attr:`SymOpList.anchor_counts`)
        counts them per orbit. Dividing by ``Z_fu`` (gcd over species of ``sum_{r in species} n_r``)
        gives the energy per formula unit:

            weight = sum_r n_r * a_r / (N * Z_fu)

        For ``Z' = 1`` single-component crystals this reduces to ``multiplicity / N`` (v1's replicas/N).

        :returns: Weight to multiply this multimer's interaction energy by
        :raises ValueError: If the multimer was not produced by :func:`~crystalatte.generate`
        """
        g = self._generation
        if g is None:
            raise ValueError("weight needs generation info; build multimers with generate()")
        total = sum(g.site_counts[r] * a for r, a in self._sym_ops.anchor_counts.items())
        return total / (g.N * g.z_fu)

    def to_molecule(self) -> qcel.models.Molecule:
        """Convert to a single QCElemental :class:`qcelemental.models.Molecule` with fragments"""
        symbols: list[str] = []
        fragments: list[list[int]] = []
        for monomer in self._monomers:
            start = len(symbols)
            symbols.extend(monomer.symbols)
            fragments.append(list(range(start, len(symbols))))

        coords = np.vstack([m._cart_coords for m in self._monomers])
        return qcel.models.Molecule(
            symbols=symbols,
            geometry=(coords / qcel.constants.bohr2angstroms).flatten(),
            fragments=fragments,
        )

    def to_monomer_molecules(self) -> list[qcel.models.Molecule]:
        """Convert to one QCElemental :class:`qcelemental.models.Molecule` per :class:`Monomer`"""
        return [monomer.to_molecule() for monomer in self._monomers]
